/**
 * Custom error thrown when a demo entity ID is accidentally passed to an API service.
 * Prevents unnecessary network calls and avoids 404 responses from backend.
 */
export class DemoModeApiError extends Error {
  public readonly isDemoBlocked = true;

  constructor(message: string = 'Network request blocked for demo entity ID') {
    super(message);
    this.name = 'DemoModeApiError';
    Object.setPrototypeOf(this, DemoModeApiError.prototype);
  }
}

/**
 * Standard UUID v4/v1 regex (case-insensitive)
 */
const UUID_REGEX = /^[0-9a-f]{8}-[0-9a-f]{4}-[1-5][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/i;

/**
 * Detects whether an ID is a known demo or simulated entity ID.
 * Examples: 'patient-001', 'patient-002', 'med-1', 'fam-1', 'apt-1', 'alt-1', 'story-1', 'ai-1', 'caretaker-001', 'demo-...'
 */
export function isDemoId(id?: string | null): boolean {
  if (!id || typeof id !== 'string') return true;
  const trimmed = id.trim();
  if (!trimmed) return true;

  return (
    trimmed === 'patient-001' ||
    trimmed === 'patient-002' ||
    trimmed === 'caretaker-001' ||
    /^patient-\d+/i.test(trimmed) ||
    /^caretaker-\d+/i.test(trimmed) ||
    /^med-\d+/i.test(trimmed) ||
    /^fam-\d+/i.test(trimmed) ||
    /^apt-\d+/i.test(trimmed) ||
    /^alt-\d+/i.test(trimmed) ||
    /^story-\d+/i.test(trimmed) ||
    /^ai-\d+/i.test(trimmed) ||
    /^demo-/i.test(trimmed)
  );
}

/**
 * Determines whether a patient ID is a valid real backend patient ID.
 * Real IDs are UUIDs or non-demo database IDs generated by the backend.
 */
export function isRealPatientId(id?: string | null): id is string {
  if (!id || typeof id !== 'string') return false;
  const trimmed = id.trim();
  if (!trimmed) return false;
  if (isDemoId(trimmed)) return false;

  // Legit UUID or valid non-demo string ID
  return UUID_REGEX.test(trimmed) || (!trimmed.startsWith('patient-') && !trimmed.startsWith('demo-') && trimmed.length >= 6);
}

/**
 * Checks whether the application or patient is currently in demo mode.
 */
export function isDemoMode(patientId?: string | null): boolean {
  return !isRealPatientId(patientId);
}

