export function getDemoPatient(id?: string): PatientProfile {
  if (id) {
    const found = DEMO_PATIENTS.find((p) => p.id === id);
    if (found) return JSON.parse(JSON.stringify(found));
  }
  return JSON.parse(JSON.stringify(INITIAL_PATIENT));
}

